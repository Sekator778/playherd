  out="$(PATH="${d}/fakebin:${PATH}" FAKE_IPT_STATE="${d}/state4" FAKE_IPT_DENY=1 bs "$(newroot rules)" "adapt_rules_file 4 '${d}/rules8.v4'; cp '${orig}' '${d}/rules8.v4'; adapt_rules_file 4 '${d}/rules8.v4'" 2>&1)"
