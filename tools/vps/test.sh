  [[ "$(grep '^HERD_OPERATOR_TOKEN=' "${f}")" == "$(grep '^HERD_OPERATOR_TOKEN=' <<<"${first}")" && "$(grep '^HERD_DB_PASSWORD=' "${f}")" == "$(grep '^HERD_DB_PASSWORD=' <<<"${first}")" ]]
