  : >"${d}/ipt.log"
  out="$(PATH="${d}/fakebin:${PATH}" FAKE_IPT_STATE="${d}/state4" FAKE_IPT_LOG="${d}/ipt.log" bs "$(newroot live)" 'adapt_live_chain 4' 2>&1)"
