#!/usr/bin/env bash
# tools/vps/test.sh -- tests of the VPS kit that need no VPS, no network and, by default, no docker.
#
#   tools/vps/test.sh                  everything except the parts that need docker
#   tools/vps/test.sh --docker         also: the Caddyfile through the pinned caddy image (validate, fmt, adapt), the same
#                                      Caddyfile served by that Caddy version's release binary in a throwaway ubuntu:24.04
#                                      container (the headers, the download path, a forged address; needs github.com),
#                                      this machine's rsync against Ubuntu's rsync server with deploy.sh's flags,
#                                      backup.sh against a real PostgreSQL 16 (dump, restore, a failed restore),
#                                      bootstrap.sh in a throwaway container, and again in one that looks like Oracle's
#                                      image (netfilter-persistent and its rules file), Oracle's rules file and the
#                                      firewall step against a real iptables-nft with probes from a second container,
#                                      and the memory settings against the JVM and PostgreSQL images -- all named
#                                      herd-vps-dryrun-*
#   tools/vps/test.sh --arm64          builds server, web and chainsvc for linux/arm64 in a throwaway buildx builder (a
#                                      few minutes on an arm64 machine; skipped on any other) and starts them
#   tools/vps/test.sh --only A,B       only these sections: static, common, deploy, env, secrets, jobs, backup, verify,
#                                      stand, flow, oracle, memory (and, with --docker: caddy, caddylive, rsynccompat,
#                                      pgrestore, bootstrap, oracleboot, firewall, memfloor; with --arm64: arm64)
#
# What is real here: the scripts, the repository files they depend on (docker-compose.yml, tools/stand.sh, web/nginx.conf,
# the Rust and Java sources whose names and log lines they use), this machine's rsync, shellcheck, openssl. What is
# faked: ssh and scp (run the "remote" command in a directory that stands for the VPS's home), docker, dig and ss
# (shell functions or scripts that answer from variables), and iptables where the kernel is not to be touched. Nothing here
# contacts a host, and no docker command runs without --docker (or --arm64).
# With --docker the containers are the caddy image's one-shot `validate`/`fmt`/`adapt`, ubuntu ones, a PostgreSQL and a JVM. Two of
# them, in the firewall test, get the capability NET_ADMIN, on a network of their own and never on the host's network; the others
# on the host's network get no capability and cannot touch the host's firewall.
#
# Like tools/test-stand.sh it prints one line per check and exits non-zero if one failed.
# HERD_VPS_TEST_DEBUG=1 also prints the output of every script run in the `flow` section; HERD_VPS_TEST_LOGDIR=DIR keeps the
# logs of the two bootstrap.sh runs. Do not edit this file while it runs: bash reads a script as it goes.

# A test script: it greps for literal ${...} text (single quotes on purpose), reads $? after [[ ]] tests, sets scratch variables in
# subshells, and sources files from paths it computes.
# shellcheck disable=SC2016,SC2030,SC2031,SC2181,SC2319,SC1091,SC2012,SC2251
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "${HERE}/../.." && pwd)"
SANDBOX="$(mktemp -d)"
DOCKER_TESTS=0
ONLY=""
FAILS=0
TOTAL=0
SKIPPED=0
KEEP_CONTAINER=0
CONTAINER=""
# what the tests that start more than one container, or a network, a builder or images, have started (herd-vps-dryrun-*): removed at the
# end of the test and, should the run be interrupted, here
EXTRA_CONTAINERS=""
EXTRA_NETWORK=""
EXTRA_BUILDER=""
EXTRA_IMAGES=""
ARM64_TESTS=0

cleanup() {
  local c
  if [[ -n "${CONTAINER}" ]] && ((!KEEP_CONTAINER)); then
    docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
  fi
  for c in ${EXTRA_CONTAINERS}; do docker rm -f "${c}" >/dev/null 2>&1 || true; done
  if [[ -n "${EXTRA_BUILDER}" ]]; then docker buildx rm --force "${EXTRA_BUILDER}" >/dev/null 2>&1 || true; fi
  for c in ${EXTRA_IMAGES}; do docker rmi -f "${c}" >/dev/null 2>&1 || true; done
  if [[ -n "${EXTRA_NETWORK}" ]]; then docker network rm "${EXTRA_NETWORK}" >/dev/null 2>&1 || true; fi
  rm -rf "${SANDBOX}"
}
trap cleanup EXIT

while (($# > 0)); do
  case "$1" in
    --docker)
      DOCKER_TESTS=1
      shift
      ;;
    --arm64)
      ARM64_TESTS=1
      shift
      ;;
    --only)
      ONLY="${2:?--only needs a list}"
      shift 2
      ;;
    --keep-container)
      KEEP_CONTAINER=1
      shift
      ;;
    -h | --help)
      sed -n '2,/^$/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "unknown argument $1" >&2
      exit 2
      ;;
  esac
done

want() { [[ -z "${ONLY}" || ",${ONLY}," == *",$1,"* ]]; }
ok() { # description, status (0 = holds)
  TOTAL=$((TOTAL + 1))
  if [[ "$2" == "0" ]]; then
    echo "ok   - $1"
  else
    echo "FAIL - $1"
    FAILS=$((FAILS + 1))
  fi
}
skip() {
  SKIPPED=$((SKIPPED + 1))
  echo "skip - $1"
}
section() { printf '\n== %s\n' "$1"; }
has() { grep -qF -- "$2" <<<"$1"; }                  # has "$text" "needle"
has_re() { grep -qE -- "$2" <<<"$1"; }               # has_re "$text" "regex"
lacks() { ! grep -qF -- "$2" <<<"$1"; }              # lacks "$text" "needle"
file_has() { grep -qF -- "$2" "$1" 2>/dev/null; }    # file_has FILE "needle"
file_has_re() { grep -qE -- "$2" "$1" 2>/dev/null; } # file_has_re FILE "regex"
mode_of() { stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1"; }
sha256_of_file() { shasum -a 256 "$1" | cut -d' ' -f1; }

# --- fakes -----------------------------------------------------------------------------------------------------------------------

MACBIN="${SANDBOX}/macbin"   # what the operator's machine has first on its PATH
VPSBIN="${SANDBOX}/vpsbin"   # the same for the "remote" side
VPSHOME="${SANDBOX}/vpshome" # the deploy user's home on the pretend VPS
SSHLOG="${SANDBOX}/ssh.log"
mkdir -p "${MACBIN}" "${VPSBIN}" "${VPSHOME}"
: >"${SSHLOG}"

# ssh: skip the options, take the target, run the rest as a command line in VPSHOME (stdin is passed through, as the real one does)
cat >"${MACBIN}/ssh" <<'EOF'
#!/usr/bin/env bash
while (($# > 0)); do
  case "$1" in
    -i | -p | -o | -l | -F | -J) shift 2 ;;
    -*) shift ;;
    *) break ;;
  esac
done
target="$1"
shift
printf '%s\t%s\n' "${target}" "$*" >>"${FAKE_SSH_LOG}"
[[ "${FAKE_SSH_FAIL:-0}" != 1 ]] || exit 255
cd "${FAKE_VPS_HOME}" || exit 255
HOME="${FAKE_VPS_HOME}" PATH="${FAKE_VPS_BIN}:${PATH}" exec /bin/bash -c "$*"
EOF
cat >"${MACBIN}/scp" <<'EOF'
#!/usr/bin/env bash
while (($# > 0)); do
  case "$1" in
    -i | -P | -o) shift 2 ;;
    -*) shift ;;
    *) break ;;
  esac
done
src="$1"
dst="$2"
printf 'scp\t%s\t%s\n' "${src}" "${dst}" >>"${FAKE_SSH_LOG}"
path="${dst#*:}"
[[ "${path}" == /* ]] || path="${FAKE_VPS_HOME}/${path}"
mkdir -p "$(dirname "${path}")"
cp "${src}" "${path}"
EOF
# docker on the operator's machine: only `info` and `ps -q` (is a chainsvc of the local stand running?)
cat >"${MACBIN}/docker" <<'EOF'
#!/usr/bin/env bash
case "$1" in
  info) exit 0 ;;
  ps) [[ "${FAKE_LOCAL_CHAINSVC:-0}" != 1 ]] || echo "0123456789ab" ;;
  *) echo "fake docker (operator side): unexpected $*" >&2; exit 99 ;;
esac
EOF
# docker on the VPS side, for data-install.sh and backup.sh
cat >"${VPSBIN}/docker" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"${FAKE_DOCKER_LOG:-/dev/null}"
case "$1" in
  info) exit 0 ;;
  ps)
    case "$*" in
      *service=chainsvc*) [[ "${FAKE_VPS_CHAINSVC:-0}" != 1 ]] || echo "chainsvc0001" ;;
      *service=db*) [[ "${FAKE_VPS_DB:-1}" != 1 ]] || echo "db0001" ;;
      *service=server*) [[ "${FAKE_VPS_SERVER:-1}" != 1 ]] || echo "serverc0001" ;;
    esac
    ;;
  volume) [[ "${FAKE_JOURNAL_VOLUME_MISSING:-0}" != 1 ]] ;;
  run)
    wc -c >>"${FAKE_JOURNAL_BYTES:-/dev/null}"
    [[ "${FAKE_JOURNAL_FAIL:-0}" != 1 ]] || exit 4
    ;;
  exec)
    case "$*" in
      *"tar -C /var/lib/herd/journal"*)
        d="$(mktemp -d)"
        printf 'journal bytes\n' >"${d}/20261021F.cq4"
        tar -C "${d}" -cf - .
        rm -rf "${d}"
        ;;
      *curl*admin/status*) printf '{"journal":{"projector":{"running":true,"lag":%s,"failures":%s}}}' "${FAKE_JOURNAL_LAG:-3}" "${FAKE_JOURNAL_FAILURES:-0}" ;;
      *pg_dump*)
        [[ "${FAKE_PGDUMP_FAIL:-0}" != 1 ]] || exit 1
        echo "-- PostgreSQL database dump"
        echo "DROP TABLE IF EXISTS public.rounds;"
        [[ "${FAKE_PGDUMP_TRUNCATED:-0}" == 1 ]] || echo "-- PostgreSQL database dump complete"
        ;;
      *psql*)
        wc -c >>"${FAKE_PSQL_BYTES:-/dev/null}"
        [[ "${FAKE_PSQL_FAIL:-0}" != 1 ]] || exit 3
        ;;
    esac
    ;;
  compose)
    case "$*" in
      *"port web 80"*) [[ -z "${FAKE_COMPOSE_PORT_WEB:-}" ]] || echo "${FAKE_COMPOSE_PORT_WEB}" ;;
      *"ps -q server"*) echo "serverc0001" ;;
      *"ps -q chainsvc"*) echo "chainsvcc0001" ;;
      *"ps -q") [[ "${FAKE_COMPOSE_NO_CONTAINERS:-0}" == 1 ]] || printf 'dbc0001\nchainsvcc0001\nserverc0001\nwebc0001\n' ;;
    esac
    ;;
  stats) printf '%s\n' "${FAKE_STATS:-}" ;;
  inspect)
    case "$*" in
      *Mounts*) printf '%s' "${FAKE_JOURNAL_VOLUME-herd_journal_live}" ;;
      *.Image*) echo "sha256:fakeimage" ;;
      *) printf 'PATH=/usr/bin\nJDK_JAVA_OPTIONS=%s\n' "${FAKE_JDK_OPTS:-}" ;;
    esac
    ;;
  *) echo "fake docker (vps side): unexpected $*" >&2; exit 99 ;;
esac
EOF
chmod +x "${MACBIN}"/* "${VPSBIN}"/*
export FAKE_SSH_LOG="${SSHLOG}" FAKE_VPS_HOME="${VPSHOME}" FAKE_VPS_BIN="${VPSBIN}"

